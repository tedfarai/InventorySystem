import { BackupSnapshot } from '../types';

export interface BackupReminderSettings {
  enabled: boolean;
  intervalDays: number;
  snoozedUntil: number | null;
  lastPromptedAt: number | null;
}

export interface BackupReminderEvaluation {
  latestBackup: BackupSnapshot | null;
  latestBackupMs: number | null;
  daysSinceLastBackup: number | null;
  hoursSinceLastBackup: number | null;
  isOverdue: boolean;
  isSnoozed: boolean;
  shouldNotify: boolean;
  thresholdDays: number;
  formattedAge: string;
}

export const BACKUP_REMINDER_STORAGE_KEY = 'xl_procurement_backup_reminders_v1';

export const DEFAULT_BACKUP_REMINDER_SETTINGS: BackupReminderSettings = {
  enabled: true,
  intervalDays: 7,
  snoozedUntil: null,
  lastPromptedAt: null,
};

export function clampIntervalDays(value: number): number {
  if (!Number.isFinite(value)) return DEFAULT_BACKUP_REMINDER_SETTINGS.intervalDays;
  return Math.min(90, Math.max(1, Math.round(value)));
}

export function loadBackupReminderSettings(): BackupReminderSettings {
  try {
    const raw = localStorage.getItem(BACKUP_REMINDER_STORAGE_KEY);
    if (!raw) return { ...DEFAULT_BACKUP_REMINDER_SETTINGS };
    const parsed = JSON.parse(raw);
    return {
      enabled: typeof parsed.enabled === 'boolean' ? parsed.enabled : DEFAULT_BACKUP_REMINDER_SETTINGS.enabled,
      intervalDays: clampIntervalDays(Number(parsed.intervalDays)),
      snoozedUntil: typeof parsed.snoozedUntil === 'number' && Number.isFinite(parsed.snoozedUntil) ? parsed.snoozedUntil : null,
      lastPromptedAt: typeof parsed.lastPromptedAt === 'number' && Number.isFinite(parsed.lastPromptedAt) ? parsed.lastPromptedAt : null,
    };
  } catch {
    return { ...DEFAULT_BACKUP_REMINDER_SETTINGS };
  }
}

export function saveBackupReminderSettings(settings: BackupReminderSettings): void {
  try {
    const sanitized: BackupReminderSettings = {
      enabled: Boolean(settings.enabled),
      intervalDays: clampIntervalDays(settings.intervalDays),
      snoozedUntil: settings.snoozedUntil ?? null,
      lastPromptedAt: settings.lastPromptedAt ?? null,
    };
    localStorage.setItem(BACKUP_REMINDER_STORAGE_KEY, JSON.stringify(sanitized));
  } catch {
    // Ignore storage quota / privacy mode errors cleanly
  }
}

/**
 * Safely parses SQLite / ISO backup timestamps such as "2026-08-19 16:30:00" (UTC)
 * or standard ISO-8601 strings into epoch milliseconds.
 */
export function parseBackupTimestampMs(timestamp: string | undefined | null): number | null {
  if (!timestamp || typeof timestamp !== 'string') return null;
  const trimmed = timestamp.trim();
  if (!trimmed) return null;

  // Match "YYYY-MM-DD HH:MM:SS" generated by ISO substrings in UTC
  if (/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(trimmed)) {
    const ms = Date.parse(`${trimmed.replace(' ', 'T')}Z`);
    return Number.isNaN(ms) ? null : ms;
  }

  const parsed = Date.parse(trimmed);
  return Number.isNaN(parsed) ? null : parsed;
}

export function formatBackupAge(elapsedMs: number | null): string {
  if (elapsedMs === null || !Number.isFinite(elapsedMs)) {
    return 'No backups recorded';
  }
  const safeMs = Math.max(0, elapsedMs);
  const totalMinutes = Math.floor(safeMs / 60_000);
  if (totalMinutes < 1) return 'Just now';
  if (totalMinutes < 60) return `${totalMinutes} min${totalMinutes === 1 ? '' : 's'} ago`;
  const totalHours = Math.floor(totalMinutes / 60);
  if (totalHours < 24) return `${totalHours} hour${totalHours === 1 ? '' : 's'} ago`;
  const totalDays = Math.floor(totalHours / 24);
  return `${totalDays} day${totalDays === 1 ? '' : 's'} ago`;
}

export function evaluateBackupReminderStatus(
  backups: BackupSnapshot[],
  settings: BackupReminderSettings,
  nowMs: number = Date.now()
): BackupReminderEvaluation {
  const thresholdDays = clampIntervalDays(settings.intervalDays);
  const thresholdMs = thresholdDays * 24 * 60 * 60 * 1000;

  let latestBackup: BackupSnapshot | null = null;
  let latestBackupMs: number | null = null;

  for (const snap of Array.isArray(backups) ? backups : []) {
    const parsedMs = parseBackupTimestampMs(snap?.timestamp);
    if (parsedMs !== null && (latestBackupMs === null || parsedMs > latestBackupMs)) {
      latestBackupMs = parsedMs;
      latestBackup = snap;
    }
  }

  const elapsedMs = latestBackupMs !== null ? Math.max(0, nowMs - latestBackupMs) : null;
  const daysSinceLastBackup = elapsedMs !== null ? elapsedMs / (24 * 60 * 60 * 1000) : null;
  const hoursSinceLastBackup = elapsedMs !== null ? elapsedMs / (60 * 60 * 1000) : null;

  const isOverdue =
    !Array.isArray(backups) ||
    backups.length === 0 ||
    latestBackupMs === null ||
    (elapsedMs !== null && elapsedMs >= thresholdMs);

  const isSnoozed = Boolean(settings.snoozedUntil && settings.snoozedUntil > nowMs);
  const shouldNotify = settings.enabled && isOverdue && !isSnoozed;

  return {
    latestBackup,
    latestBackupMs,
    daysSinceLastBackup,
    hoursSinceLastBackup,
    isOverdue,
    isSnoozed,
    shouldNotify,
    thresholdDays,
    formattedAge: formatBackupAge(elapsedMs),
  };
}
